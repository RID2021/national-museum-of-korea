const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const ids = ["pensive-1", "pensive-2", "guide-robot", "hou-bronze-bowl", "baekje-landscape-brick", "gaya-armor-helmet", "hwangnam-gold-crown", "jinheung-stele"];
const portraits = {};
for (const id of ids) {
  const key = `../images/npc/national-museum/night-guard/${id}-portrait-v1.png`;
  const png = fs.readFileSync(path.resolve(root, "res/html", key));
  portraits[key] = `data:image/png;base64,${png.toString("base64")}`;
}
// ZEP widget images need embedded data or a publicly hosted URL. Preserve the
// existing UI source, but make the museum dialogue independent of a CDN.
// Official example: docs.zep.us/.../zep-script-example-code/sidebar-app
const templatePath = path.join(root, "res/html/museum-npc-widget.template.html");
let html = fs.readFileSync(templatePath, "utf8");
if (!html.includes("<script>") || !html.includes("profileImageElement.src = portraitUrl;")) {
  throw new Error("Existing dialogue widget changed; review museum embedding anchors.");
}
html = html.replace(/data:video\/mp4;base64,[A-Za-z0-9+/=]+/g, "");
html = html.replace("<script>", `<script>\nconst MUSEUM_PORTRAITS = ${JSON.stringify(portraits)};`);
html = html.replace("profileImageElement.src = portraitUrl;", "profileImageElement.src = MUSEUM_PORTRAITS[portraitUrl] || portraitUrl;");
html = "<!-- Generated by scripts/build-museum-widget.cjs; edit the builder or source template. -->\n" + html;
fs.writeFileSync(path.join(root, "res/html/museum-npc-widget-v1.html"), html);
process.stdout.write(`Embedded ${ids.length} museum portraits in the dialogue widget.\n`);

const brickNames = ["산수문전", "산수봉황문전", "산수귀문전", "연대귀문전", "연화문전", "와운문전", "반룡문전", "봉황문전"];
const brickFiles = ["landscape", "landscape-phoenix", "landscape-dokkaebi", "lotus-dokkaebi", "lotus", "lotus-cloud", "dragon", "phoenix"];
const bricks = {};
brickFiles.forEach((id, index) => {
  const png = fs.readFileSync(path.join(root, "res/images/baekje-bricks", `${id}.png`));
  bricks[brickNames[index]] = `data:image/png;base64,${png.toString("base64")}`;
});
const gameTemplate = fs.readFileSync(path.join(root, "res/html/museum-game.template.html"), "utf8");
if (!gameTemplate.includes("/* BRICK_ASSETS */")) throw new Error("Missing brick embedding anchor");
if (!gameTemplate.includes("/* SILLA_MAP_ASSET */")) throw new Error("Missing Silla map embedding anchor");
const sillaMap = fs.readFileSync(path.join(root, "res/images/national-museum/silla-map-v2.webp"));
const sillaMapAsset = `data:image/webp;base64,${sillaMap.toString("base64")}`;
fs.writeFileSync(path.join(root, "res/html/museum-game-v1.html"),
  "<!-- Generated by scripts/build-museum-widget.cjs; edit museum-game.template.html. -->\n" +
  gameTemplate
    .replace("/* BRICK_ASSETS */", `const BRICK_ASSETS = ${JSON.stringify(bricks)};`)
    .replace("/* SILLA_MAP_ASSET */", `const SILLA_MAP_ASSET = ${JSON.stringify(sillaMapAsset)};`));
process.stdout.write(`Embedded ${brickFiles.length} brick illustrations in the game widget.\n`);
process.stdout.write("Embedded the Silla map illustration in the game widget.\n");
